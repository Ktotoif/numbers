numbers = []          # список для введённых чисел
count = 0             # счётчик успешных вводов
print("Напишите 5 чисел:")

while count < 5:      # пока не наберём 5 чисел
    user_num = input(f"Введите число {count + 1}: ")
    try:
        num = int(user_num)       # пробуем преобразовать в число
        numbers.append(num)       # добавляем в список
        count += 1                # счётчик растёт только при успехе
    except ValueError:
        print("Обнаружены буквы или спецсимволы. Введите корректное число.")

print("Исходный массив чисел:", numbers)
print("Самое маленькое число:", min(numbers))   # встроенная функция
print("Самое большое число:", max(numbers))     # встроенная функция